// @ts-check
import { configs, ignores } from '@piplup/code-infra/eslint';
import { defineConfig, globalIgnores } from 'eslint/config';

// Headless enforcement (PLAN.md §1.1): ban DOM/browser globals anywhere in
// packages/core so the library can never silently gain a runtime dependency
// on a browser or Node-specific host object. Examples/ are exempt.
const BANNED_GLOBALS = [
  'document',
  'window',
  'navigator',
  'HTMLElement',
  'localStorage',
  'sessionStorage',
  'location',
  'history',
  'alert',
  'confirm',
  'prompt',
];

export default defineConfig(
  ignores(import.meta.dirname),
  globalIgnores([
    'third_party/**',
    '.build-deps/**',
    // Plain Node CommonJS maintenance scripts for the golden cross-check (see
    // test/golden/README.md), not part of the TS/ESM app.
    'test/golden/cpp-harness/**/*.cjs',
    // Node.js utility scripts, not part of the ESM library.
    'scripts/**',
    // Generated by scripts/gen-fallback.ts.
    'packages/core/src/data/fallback.ts',
  ]),
  configs.recommended,
  {
    extends: [configs.test],
    files: ['**/*.test.ts', '**/*.test.tsx', '**/test/**/*.ts'],
  },
  {
    files: ['**/*.test.ts', '**/*.test.tsx', '**/test/**/*.ts'],
    rules: {
      // validator.test.ts asserts through its expectSameProblems helper.
      'vitest/expect-expect': ['error', { assertFunctionNames: ['expect', 'expectSameProblems'] }],
    },
  },
  {
    rules: {
      // Authorship is not recorded in package.json for this project.
      'package-json/require-attribution': 'off',
      'package-json/require-author': 'off',
      // The packages use the automatic JSX runtime.
      'react/react-in-jsx-scope': 'off',
    },
  },
  {
    // The CLI example prints its output.
    files: ['examples/node-cli/**'],
    rules: { 'no-console': 'off' },
  },
  {
    files: ['packages/core/src/**/*.ts'],
    rules: {
      'no-restricted-globals': [
        'error',
        // From code-infra.
        'isFinite',
        'isNaN',
        ...BANNED_GLOBALS.map((name) => ({
          message:
            'Headless library code must not reference browser/DOM globals. ' +
            'Inject the capability instead (see PLAN.md §1).',
          name,
        })),
      ],
    },
  },
  {
    files: ['**/*.test.ts', '**/test/**/*.ts'],
    rules: {
      'no-restricted-globals': ['error', 'isFinite', 'isNaN'],
    },
  },
);
